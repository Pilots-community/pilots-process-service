    @Test
    void patchServiceInstance_invokesSetVariablesAndCompleteTask_returns200() throws Exception {
        UUID instanceId = UUID.randomUUID();
        String flowableId = "2501";

        // --- Process-instance query chain ---
        ProcessInstance mockPi = mock(ProcessInstance.class);
        when(mockPi.getId()).thenReturn(flowableId);
        when(mockPi.getProcessDefinitionKey()).thenReturn("urn:example:process");

        ProcessInstanceQuery mockPiQuery = mock(ProcessInstanceQuery.class);
        when(runtimeService.createProcessInstanceQuery()).thenReturn(mockPiQuery);
        when(mockPiQuery.processInstanceBusinessKey(instanceId.toString())).thenReturn(mockPiQuery);
        when(mockPiQuery.singleResult()).thenReturn(mockPi);

        // Variables (including _version=1 for ETag check)
        when(runtimeService.getVariables(flowableId))
                .thenReturn(Map.of("orderId", "123", "_version", 1, "_state", "STARTED", "_stakeholders", "[]"));

        // --- Task query chain ---
        Task mockTask = mock(Task.class);
        when(mockTask.getId()).thenReturn("task-001");

        TaskQuery mockTaskQuery = mock(TaskQuery.class);
        when(taskService.createTaskQuery()).thenReturn(mockTaskQuery);
        when(mockTaskQuery.processInstanceId(flowableId)).thenReturn(mockTaskQuery);
        when(mockTaskQuery.singleResult()).thenReturn(mockTask);

        mockMvc.perform(patch("/serviceInstances/" + instanceId)
                        .contentType(MediaType.APPLICATION_JSON)
                        .header("If-Match", "\"1\"")
                        .content("""
                                {
                                  "parameters": {"status": "approved"},
                                  "state": "APPROVED"
                                }
                                """))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.id").value(instanceId.toString()))
                .andExpect(jsonPath("$.state").value("APPROVED"))
                .andExpect(jsonPath("$.version").value(2));

        // setVariables must be called exactly once with the Flowable process ID
        verify(runtimeService, times(1)).setVariables(eq(flowableId), anyMap());
        // The active task must be completed to advance the process
        verify(taskService, times(1)).complete("task-001");
    }

    @Test
    void patchServiceInstance_triggersReceiveTask_whenNoUserTaskFound_returns200() throws Exception {
        UUID instanceId = UUID.randomUUID();
        String flowableId = "2501";

        // --- Process-instance query chain ---
        ProcessInstance mockPi = mock(ProcessInstance.class);
        when(mockPi.getId()).thenReturn(flowableId);
        when(mockPi.getProcessDefinitionKey()).thenReturn("urn:example:process");

        ProcessInstanceQuery mockPiQuery = mock(ProcessInstanceQuery.class);
        when(runtimeService.createProcessInstanceQuery()).thenReturn(mockPiQuery);
        when(mockPiQuery.processInstanceBusinessKey(instanceId.toString())).thenReturn(mockPiQuery);
        when(mockPiQuery.singleResult()).thenReturn(mockPi);

        when(runtimeService.getVariables(flowableId)).thenReturn(Map.of());

        // --- No user task (process is at a receiveTask) ---
        TaskQuery mockTaskQuery = mock(TaskQuery.class);
        when(taskService.createTaskQuery()).thenReturn(mockTaskQuery);
        when(mockTaskQuery.processInstanceId(flowableId)).thenReturn(mockTaskQuery);
        when(mockTaskQuery.singleResult()).thenReturn(null);

        // --- Execution query chain (receiveTask waiting execution) ---
        Execution mockExecution = mock(Execution.class);
        when(mockExecution.getId()).thenReturn("exec-001");

        ExecutionQuery mockExecQuery = mock(ExecutionQuery.class);
        when(runtimeService.createExecutionQuery()).thenReturn(mockExecQuery);
        when(mockExecQuery.processInstanceId(flowableId)).thenReturn(mockExecQuery);
        when(mockExecQuery.onlyChildExecutions()).thenReturn(mockExecQuery);
        when(mockExecQuery.singleResult()).thenReturn(mockExecution);

        mockMvc.perform(patch("/serviceInstances/" + instanceId)
                        .contentType(MediaType.APPLICATION_JSON)
                        .header("If-Match", "\"1\"")
                        .content("""
                                {"state": "COMPLETED"}
                                """))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.id").value(instanceId.toString()))
                .andExpect(jsonPath("$.state").value("COMPLETED"));

        // receiveTask must be resumed via runtimeService.trigger, not taskService.complete
        verify(runtimeService, times(1)).trigger("exec-001");
        verify(taskService, never()).complete(anyString());
    }

