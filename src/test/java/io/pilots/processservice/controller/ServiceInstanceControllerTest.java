    @Test
    void createServiceInstance_returns201_withUuidIdAndStartedState() throws Exception {
        // Flowable returns an internal process instance with a numeric ID.
        // The public UUID is generated by the controller and used as businessKey.
        ProcessInstance mockPi = mock(ProcessInstance.class);
        when(mockPi.getId()).thenReturn("2501");

        when(runtimeService.startProcessInstanceByKey(anyString(), anyString(), anyMap()))
                .thenReturn(mockPi);

        mockMvc.perform(post("/serviceInstances")
                        .contentType(MediaType.APPLICATION_JSON)
                        .content("""
                                {
                                  "serviceDefinition": "urn:example:process",
                                  "stakeholders": [
                                    {"role": "customer", "party": "did:web:example.com"}
                                  ],
                                  "parameters": {"orderId": "123"}
                                }
                                """))
                .andExpect(status().isCreated())
                // Location header must point to the newly created resource by UUID
                .andExpect(header().string("Location",
                        matchesPattern(".*/serviceInstances/" + UUID_REGEX)))
                // Response body must echo a valid UUID as id
                .andExpect(jsonPath("$.id", matchesPattern(UUID_REGEX)))
                .andExpect(jsonPath("$.serviceDefinition").value("urn:example:process"))
                // Default state when none is supplied in the request
                .andExpect(jsonPath("$.state").value("STARTED"))
                .andExpect(jsonPath("$.version").value(1));
    }

