    @Test
    void replaceServiceInstance_returns200_andIncrementsVersion() throws Exception {
        UUID instanceId = UUID.randomUUID();
        String flowableId = "6001";

        ProcessInstance mockPi = mock(ProcessInstance.class);
        when(mockPi.getId()).thenReturn(flowableId);
        when(mockPi.getProcessDefinitionKey()).thenReturn("urn:example:process");
        mockPiQueryReturning(instanceId, mockPi);

        // Current vars: one old parameter (orderId) that will be replaced
        when(runtimeService.getVariables(flowableId))
                .thenReturn(Map.of("_version", 1, "_state", "STARTED", "_stakeholders", "[]", "orderId", "old"));

        // No active user task
        TaskQuery mockTaskQuery = mock(TaskQuery.class);
        when(taskService.createTaskQuery()).thenReturn(mockTaskQuery);
        when(mockTaskQuery.processInstanceId(flowableId)).thenReturn(mockTaskQuery);
        when(mockTaskQuery.singleResult()).thenReturn(null);

        ExecutionQuery mockExecQuery = mock(ExecutionQuery.class);
        when(runtimeService.createExecutionQuery()).thenReturn(mockExecQuery);
        when(mockExecQuery.processInstanceId(flowableId)).thenReturn(mockExecQuery);
        when(mockExecQuery.onlyChildExecutions()).thenReturn(mockExecQuery);
        when(mockExecQuery.singleResult()).thenReturn(null);

        mockMvc.perform(put("/serviceInstances/" + instanceId)
                        .contentType(MediaType.APPLICATION_JSON)
                        .header("If-Match", "\"1\"")
                        .content("""
                                {
                                  "serviceDefinition": "urn:example:process",
                                  "stakeholders": [{"role": "customer", "party": "did:web:example.com"}],
                                  "parameters": {"newParam": "value"},
                                  "state": "ACTIVE"
                                }
                                """))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.id").value(instanceId.toString()))
                .andExpect(jsonPath("$.version").value(2))
                .andExpect(jsonPath("$.state").value("ACTIVE"))
                .andExpect(jsonPath("$.parameters.newParam").value("value"));

        // Old parameter key (orderId) must be removed; new variables set
        verify(runtimeService, times(1)).removeVariables(eq(flowableId), argThat(c -> c.contains("orderId")));
        verify(runtimeService, times(1)).setVariables(eq(flowableId), anyMap());
    }

